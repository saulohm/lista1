"""Faça um Programa que calcule a área de um quadrado, em seguida mostre o dobro desta área para o usuário."""
#entrada de dados
lado=float(input("digite um lado do quadrado. No lugar de vírgula, use ponto:"))
#processamento de dados
area=lado*2
resultado=area*2
#saída dos dados
print("O dobro da área do quadrado que você digitou é: ",resultado)